-- 회원. 이메일 가입이면 password_hash, 구글 가입이면 google_sub 가 채워진다 (둘 다일 수도 있다)
create table member
(
    id            bigint generated by default as identity primary key,
    email         varchar(254) not null unique,
    password_hash varchar(100),
    google_sub    varchar(64) unique,
    name          varchar(30)  not null,
    created_at    timestamp    not null,
    updated_at    timestamp    not null
);

-- 탭은 한 회원의 것이다. 메모는 탭을 통해 주인이 정해지므로 note 에는 따로 두지 않는다
alter table index_tab add column member_id bigint;
alter table index_tab add constraint fk_index_tab_member foreign key (member_id) references member (id);
create index idx_index_tab_member on index_tab (member_id, position);
