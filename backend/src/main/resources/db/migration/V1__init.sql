-- 인덱스 탭: 메모장 옆에 붙이는 색깔 견출지
create table index_tab
(
    id         bigint generated by default as identity primary key,
    name       varchar(20) not null,
    color      varchar(20) not null,
    position   int         not null,
    created_at timestamp   not null,
    updated_at timestamp   not null
);

-- 메모: 하나의 탭에 속한다 (탭 1 : N 메모)
create table note
(
    id         bigint generated by default as identity primary key,
    tab_id     bigint         not null references index_tab (id),
    title      varchar(100)   not null,
    content    varchar(10000) not null default '',
    pinned     boolean        not null default false,
    created_at timestamp      not null,
    updated_at timestamp      not null
);

-- "이 탭의 메모를 고정 먼저, 최근 수정순으로" 조회를 빠르게
create index idx_note_tab_list on note (tab_id, pinned, updated_at);
